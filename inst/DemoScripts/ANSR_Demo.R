#### 2.2 Once you have created your ANSIS account you need to keep these details somewhere to supply to the ANSR package.
####     A convenient way to store the deatils and keep them from being shared accidentally is to create an entry
####     in your "R.environ" file in your home directory on your local machine as per below.

ANSISUser='YourANSISUserName'
ANSISPassword='YourANSISPassword'

####    Then you can retrieve the values into your current session using

username <- Sys.getenv("ANSISUser")
password <- Sys.getenv("ANSISPassword")

####    Or you can just hard code them into this script.

username = 'YourANSISUserName'
password = 'YourANSISPassword'

####  3. Now we need to Authenticate with the ANSIS API using the apiAuthoriseMe() function. This function also
####     Sets up a directory where all of the ANSIS data downloads will be wrtten automatically

DataStorePath = 'c:/temp/ansis'
apiAuthoriseMe(username = username, password = password, DataStorePath = DataStorePath)

####  4. OK you are good to go. All ANSIS data requests via the ANSIS API have a similar workflow
####     1 - Generate an ANSIS query JSON object
####     2 - Send this request to the API
####     3 - Check with the API to determine when the query has finished processing on the ANSIS server
####     4 - Download the JSON files generated by the query and ad them to a zip file - one per query
####     5 - Parse these JSON files into a flat file (csv) structure

####   The ANSR package provides functions to undertake all of these steps individually or you can use a wrapper function
####   to run all of these steps in sequence.

####  4.1 Run the wrapper function below to undertake the query process in one command.

AnsisDataObject <- apiGetANSISData(queryName='ANSISDemo', description = "This is a description of the purpose of the query",
                       minx=147, maxx=151, miny=-29, maxy=-25, provider = 'CSIRO', ansisProperties=c('Concentration of organic Carbon', 'pH', 'Texture'),
                       overwrite=T, parseAll = F, verbose=T, viewSummaries=T)

#### This function returns a list of ANSIS data and some summary info
