####  So that is it.
####  You can now jump out out start downloading all the lovely soil data in ANSIS or you can read a bit further and see some more of the details .




####  5. Below are the functions needed to run the above query as a series of manual steps.

####  5.1 Send the query to the ANSIS server.

qry <- apiSendQuery(minx = 147, maxx = 151, miny = -29, maxy = -25,
                      provider = 'CSIRO', ansisProperties=c('Concentration of organic Carbon', 'pH', 'Texture'),
                      endYear = 2026)

####  5.2 Monitor when the query has finished running on the server.

apiQueryStatus_Monitor(reqID = qry$reqID)

####  5.3 Once the query is completed download the generated JSON files

zipFile <- tempfile(pattern = 'ANSIS_Query', fileext = '.zip')
apiDownloadQueryData(reqID = qry$reqID, outZipFile = zipFile)  # - ok

####  5.4 Parse the JSON files into a flat file structure.

ado <- parseANSISJsonParallel3(zipFile = zipFile, numCPUs = NULL,
                        propertiesToParse = NULL, verbose = F,
                        parseAll = T, viewSummaries = T)



####  OK. That is the manual approach. Note that the JSON parsing uses multiple cores on your machine to speed up the flat file generation.
####      Run this package on a machine with as many cores as possible to optimise your parsing experience.



